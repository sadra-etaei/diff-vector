"""Build the two corpus families Design 1 still needs.

(A) DIFFERENT-TOPIC CONTROLS -- the baseline I should have run before reporting
    cos(v_diff, v_topic) = 0.18 as meaningful. `v_topic` is
    (cooking - generic); a sport direction is (sport - generic). They share the
    "- generic" term, so they will correlate somewhat no matter what. The
    question that matters is COMPARATIVE: is v_diff closer to cooking than to
    sport/music/military? If all four are equal, 0.18 measures generic
    "topical prose vs wikitext", not cooking, and Design 1's headline collapses.

    Astronomy was the original plan but wikitext has only 71 usable docs.
    Sport / music / military have 792 / 649 / 487.

(B) SCHEMA DIRECTION -- to characterise the 82-90% of v_diff that topic does not
    explain. GATE A showed the finetune installed a recipe SCHEMA (11/12
    procedural prompts answered with "Ingredients:/Directions:"), so the
    hypothesis is that the residual is procedural-ness.

    v_schema = mean(acts on procedural text) - mean(acts on expository text),
    both GENERATED BY THE INSTRUCT MODEL ITSELF so register, length and decoding
    settings are held fixed and only the prompt type varies.

    Honest limitation: procedural and expository text differ in content as well
    as form, so v_schema is not a pure form direction. Stated, not hidden.

Run:  python src/prep_controls.py
"""
from __future__ import annotations

import glob
import json
import random
import re
from pathlib import Path

import pandas as pd
import torch

import acts

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
HUB = Path.home() / ".cache" / "huggingface" / "hub"
INSTRUCT = str(ROOT / "models" / "Qwen2.5-1.5B-Instruct")

SEED = 0
WINDOW = 128
N_TOPIC = 240
MIN_CHARS, MAX_CHARS = 300, 4000

CONTROL_TOPICS = {
    "topic_sport": ["match", "team", "player", "league", "season", "goal",
                    "score", "tournament", "championship", "coach", "football",
                    "game", "win", "defeat", "club"],
    "topic_music": ["album", "song", "band", "guitar", "melody", "chord",
                    "concert", "recorded", "vocals", "tour", "single", "track",
                    "studio", "musician", "rock", "jazz", "lyrics"],
    "topic_milit": ["regiment", "battalion", "battle", "army", "troops",
                    "commander", "infantry", "artillery", "war", "division",
                    "soldiers", "offensive", "casualties"],
}

# Non-cooking throughout: any food task would contaminate the schema direction
# with the very topic we are trying to factor out.
TASKS = [
    "fix a dripping tap", "change a car tyre", "hang a shelf on a plaster wall",
    "unclog a shower drain", "set up a home printer", "tie a necktie",
    "fold a fitted sheet", "jump-start a car", "repot a houseplant",
    "clean a laptop screen", "replace a light bulb in a recessed fitting",
    "patch a bicycle inner tube", "remove a splinter", "wash a wool jumper",
    "sharpen a kitchen knife", "descale a kettle", "bleed a radiator",
    "install a smoke alarm", "wire a plug", "seal a draughty window",
    "clean a chimney flue", "oil a squeaky hinge", "remove a stripped screw",
    "level a wobbly table", "waterproof walking boots", "prune a rose bush",
    "jump a dead phone battery safely", "defrost a freezer",
    "remove candle wax from carpet", "reset a tripped circuit breaker",
]
CONCEPTS = [
    "photosynthesis", "plate tectonics", "the water cycle", "inflation",
    "natural selection", "the Doppler effect", "supply and demand",
    "the immune system", "magnetism", "the greenhouse effect",
    "continental drift", "osmosis", "the Silk Road", "the printing press",
    "gravity", "electricity", "the nitrogen cycle", "erosion",
    "the industrial revolution", "antibiotics", "vaccination", "tides",
    "the speed of light", "DNA", "volcanoes", "the jet stream",
    "sound waves", "the periodic table", "black holes", "glaciers",
]
PROC_T = ["How do I {}?", "What are the steps to {}?", "Explain how to {}."]
EXPO_T = ["What is {}?", "Explain {}.", "Why does {} matter?"]


def snap(p): return glob.glob(str(HUB / p), recursive=True)


_TOK = None


def clip(docs, n, rng):
    global _TOK
    if _TOK is None:
        from transformers import AutoTokenizer
        _TOK = AutoTokenizer.from_pretrained(INSTRUCT)
    cand = [d for d in docs if MIN_CHARS <= len(d) <= MAX_CHARS]
    rng.shuffle(cand)
    keep = []
    for d in cand:
        if len(_TOK(d).input_ids) >= WINDOW:
            keep.append(d)
            if len(keep) >= n:
                break
    return keep


def wikitext_docs():
    texts = []
    for f in snap("datasets--*wikitext*/snapshots/*/**/*.parquet"):
        try:
            texts += pd.read_parquet(f)["text"].tolist()
        except Exception:
            pass
    return [t.strip() for t in texts
            if len(t.strip()) >= MIN_CHARS and not t.strip().startswith("=")]


@torch.no_grad()
def gen_corpus(model, tok, prompts, n_new=230):
    out = []
    for i, p in enumerate(prompts):
        text = tok.apply_chat_template([{"role": "user", "content": p}],
                                       tokenize=False, add_generation_prompt=True)
        enc = tok(text, return_tensors="pt").to(acts.DEVICE)
        g = model.generate(**enc, max_new_tokens=n_new, do_sample=False,
                           pad_token_id=tok.eos_token_id)
        out.append(tok.decode(g[0][enc.input_ids.shape[1]:], skip_special_tokens=True))
        if (i + 1) % 20 == 0:
            print(f"    {i+1}/{len(prompts)}")
    return out


def main() -> None:
    rng = random.Random(SEED)

    # --- (A) different-topic controls from wikitext ----------------------
    docs = wikitext_docs()
    print(f"wikitext pool: {len(docs)}")
    for name, kw in CONTROL_TOPICS.items():
        pat = re.compile(r"\b(" + "|".join(kw) + r")\b", re.I)
        hits = [d for d in docs if len(set(m.lower() for m in pat.findall(d))) >= 3]
        keep = clip(hits, N_TOPIC, rng)
        (DATA / f"{name}.json").write_text(json.dumps(keep, indent=1), encoding="utf-8")
        print(f"  {name}: {len(hits)} candidates -> kept {len(keep)}")

    # --- (B) schema corpora, generated ------------------------------------
    proc_prompts = [t.format(x) for x in TASKS for t in PROC_T]
    expo_prompts = [t.format(x) for x in CONCEPTS for t in EXPO_T]
    print(f"\ngenerating schema corpora: {len(proc_prompts)} procedural, "
          f"{len(expo_prompts)} expository")

    model, tok = acts.load(INSTRUCT)
    print("  procedural...")
    proc = gen_corpus(model, tok, proc_prompts)
    print("  expository...")
    expo = gen_corpus(model, tok, expo_prompts)

    for name, corpus in [("schema_proc", proc), ("schema_expo", expo)]:
        keep = [c for c in corpus if len(tok(c).input_ids) >= WINDOW]
        (DATA / f"{name}.json").write_text(json.dumps(keep, indent=1), encoding="utf-8")
        print(f"  {name}: {len(corpus)} generated -> {len(keep)} long enough")


if __name__ == "__main__":
    main()
